import { Document, HeadingLevel, Packer, Paragraph, TextRun } from 'docx';
import type { DocumentContent } from '../ai/types';

export async function buildDocx(content: DocumentContent): Promise<Buffer> {
  const children: Paragraph[] = [
    new Paragraph({ text: content.title, heading: HeadingLevel.TITLE }),
    new Paragraph({
      children: [
        new TextRun({
          text: 'Generated by AI Business Assistant (prototype) - review before use.',
          italics: true,
          size: 16,
          color: '64748B',
        }),
      ],
    }),
    new Paragraph({ text: '' }),
  ];

  for (const section of content.sections) {
    children.push(
      new Paragraph({ text: section.heading, heading: HeadingLevel.HEADING_1 }),
    );
    for (const paragraph of section.paragraphs) {
      children.push(new Paragraph(paragraph));
    }
    for (const bullet of section.bullets) {
      children.push(new Paragraph({ text: bullet, bullet: { level: 0 } }));
    }
  }

  const doc = new Document({ sections: [{ properties: {}, children }] });
  const buffer = await Packer.toBuffer(doc);
  return Buffer.from(buffer);
}
